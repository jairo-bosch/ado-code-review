use serde_json::json;

use super::*;

pub(in crate::app::review) fn fixture() -> Context {
    Context {
        details: serde_json::from_value(json!({"title":"Synthetic review"})).unwrap(),
        threads: vec![
            serde_json::from_value(json!({"id":4,"status":"active","comments":[]})).unwrap(),
        ],
        files: vec![ReviewFile {
            tracking_id: None,
            path: "src/lib.rs".into(),
            previous_path: None,
            hunks: diff::hunks("first\nold\nlast\n", "first\nnew\nlast\n"),
            new_content: None,
        }],
        skipped: vec![SkippedFile {
            path: "Cargo.lock".into(),
            reason: SkippedReason::DefaultExcluded,
        }],
        instructions: Vec::new(),
    }
}

#[test]
fn excludes_paths_before_loading_renamed_source() {
    let exclusions = Exclusions::new(&["internal/**".into()]).unwrap();
    let mut collector = FileCollector {
        exclusions: &exclusions,
        budget: Budget {
            diff: 100,
            content: 100,
        },
    };
    let change = FileChange {
        tracking_id: None,
        path: "/src/open.txt".into(),
        before: Some("/internal/private.txt".into()),
        after: true,
    };
    let result = collector
        .collect(&change, |_, _| panic!("excluded file must not be fetched"))
        .unwrap();
    assert!(matches!(result, Err(SkippedReason::UserExcluded)));
}

#[test]
fn content_budget_drops_whole_files_but_keeps_the_diff() {
    let change = FileChange {
        tracking_id: None,
        path: "/src/example.rs".into(),
        before: None,
        after: true,
    };
    let sides: (Vec<u8>, Vec<u8>) = (Vec::new(), "éé\n".as_bytes().to_vec());
    let mut budget = Budget {
        diff: 100,
        content: 2,
    };
    let Ok(file) = build_file(&change, sides, &mut budget) else {
        panic!("the diff fits");
    };
    assert!(file.new_content.is_none());
    assert!(file.hunks[0].contains_change(1, 1));
    assert_eq!(budget.content, 2);
}

#[test]
fn skips_binary_and_generated_content() {
    assert!(matches!(
        source_text(vec![b'x', 0]),
        Err(SkippedReason::Binary)
    ));
    assert!(matches!(
        source_text(b"// Code generated by test; DO NOT EDIT.\nfunction()".to_vec()),
        Err(SkippedReason::Generated)
    ));
    assert!(source_text(b"let text = \"do not edit\";".to_vec()).is_ok());
}
